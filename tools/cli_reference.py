#!/usr/bin/env python3
"""Generate docs/cli-reference.md from the kit's real argparse parsers, so the reference cannot drift.

    python tools/cli_reference.py            # print the reference
    python tools/cli_reference.py --write    # (re)write docs/cli-reference.md
    python tools/cli_reference.py --check    # exit 1 when docs/cli-reference.md is not current

The parsers are built exactly as ``n64dk.cli.main`` builds them: every module of ``n64dk.commands``
is imported (``load_commands``), and each registered command's ``arguments(parser)`` adds its
options.  The output depends only on those definitions (no terminal width, no environment), so
the file is reproducible; ``tests/test_doc_examples.py`` fails when it is out of date.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "cli-reference.md"
HEADER = ("<!-- Generated by tools/cli_reference.py from the argparse parsers of n64dk.commands. "
          "Do not edit: run `python tools/cli_reference.py --write`. -->")


def _load():
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from n64dk import cli
    cli.load_commands()
    return cli


def command_parsers() -> dict[str, tuple[argparse.ArgumentParser, str]]:
    """``{name: (parser, help)}`` for every registered command, built as ``cli.main`` builds them."""
    cli = _load()
    out = {}
    for name, (fn, _unused, help_text) in sorted(cli.COMMANDS.items()):
        parser = argparse.ArgumentParser(prog=f"n64dk {name}", add_help=False)
        arguments = getattr(fn, "arguments", None)
        if arguments:
            arguments(parser)
        out[name] = (parser, help_text)
    return out


def build_parser() -> argparse.ArgumentParser:
    """The complete ``n64dk`` parser, as ``cli.main`` builds it (for parse-only checks)."""
    cli = _load()
    parser = argparse.ArgumentParser(prog="n64dk", description=cli.__doc__)
    parser.add_argument("--format", choices=("text", "json"), default="text")
    sub = parser.add_subparsers(dest="command", required=True)
    for name, (fn, _unused, help_text) in sorted(cli.COMMANDS.items()):
        p = sub.add_parser(name, help=help_text)
        arguments = getattr(fn, "arguments", None)
        if arguments:
            arguments(p)
        p.set_defaults(_fn=fn)
    return parser


def _cell(text) -> str:
    """One markdown table cell: whitespace collapsed, pipes escaped."""
    return " ".join(str(text or "").split()).replace("|", "\\|")


def _metavar(action: argparse.Action) -> str:
    if action.metavar:
        return action.metavar if isinstance(action.metavar, str) else " ".join(action.metavar)
    if action.choices:
        return "{" + ",".join(str(c) for c in action.choices) + "}"
    return action.dest.upper() if action.option_strings else action.dest


def _value(action: argparse.Action) -> str:
    if action.nargs == 0:
        return ""
    name = _metavar(action)
    return {None: name, "?": f"[{name}]", "*": f"[{name} ...]", "+": f"{name} [{name} ...]",
            argparse.REMAINDER: "..."}.get(action.nargs, " ".join([name] * action.nargs)
                                           if isinstance(action.nargs, int) else name)


def _help(action: argparse.Action, prog: str) -> str:
    text = action.help or ""
    if text == argparse.SUPPRESS:
        return ""
    try:
        text = text % dict(vars(action), prog=prog)
    except (KeyError, TypeError, ValueError):
        pass
    return _cell(text)


def _default(action: argparse.Action) -> str:
    value = action.default
    if value is None or value is False or value == [] or value == argparse.SUPPRESS or action.nargs == 0:
        return ""
    if isinstance(value, bool):
        return str(value).lower()
    return "`" + _cell(repr(value) if isinstance(value, str) else value) + "`"


def usage(name: str, parser: argparse.ArgumentParser) -> str:
    parts = [f"n64dk {name}"]
    for action in parser._actions:
        if isinstance(action, argparse._HelpAction):
            continue
        if action.option_strings:
            flag = action.option_strings[0] if len(action.option_strings[0]) > 2 or len(action.option_strings) == 1 \
                else action.option_strings[-1]
            text = f"{flag} {_value(action)}".strip()
            parts.append(text if action.required else f"[{text}]")
        else:
            parts.append(_value(action))
    return " ".join(parts)


def render() -> str:
    parsers = command_parsers()
    lines = [HEADER, "", "# n64dk command reference", "",
             "Every command, its arguments and defaults, read from the parsers themselves. Global option:",
             "`--format text|json` goes before the command name (`n64dk --format json info ROM`).", "",
             f"{len(parsers)} commands.", "", "| command | what it does |", "|---|---|"]
    for name, (_parser, help_text) in parsers.items():
        summary = _cell(help_text)
        lines.append(f"| [`{name}`](#{name}) | {summary} |")
    for name, (parser, help_text) in parsers.items():
        lines += ["", f"## {name}", "", " ".join((help_text or "").split()), "", "```text",
                  usage(name, parser), "```"]
        rows = [a for a in parser._actions if not isinstance(a, argparse._HelpAction)]
        if not rows:
            continue
        lines += ["", "| argument | value | required | default | description |", "|---|---|---|---|---|"]
        for action in rows:
            label = ", ".join(f"`{s}`" for s in action.option_strings) or f"`{action.dest}` (positional)"
            value = _value(action)
            required = (action.required if action.option_strings
                        else action.nargs not in ("?", "*", argparse.OPTIONAL, argparse.ZERO_OR_MORE))
            lines.append(f"| {label} | {('`' + value + '`') if value else ''} | "
                         f"{'yes' if required else ''} | "
                         f"{_default(action)} | {_help(action, parser.prog)} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help=f"write {TARGET.relative_to(ROOT)}")
    group.add_argument("--check", action="store_true", help="exit 1 when the file is not current")
    args = parser.parse_args(argv)
    text = render()
    if args.write:
        TARGET.write_text(text)
        print(f"wrote {TARGET.relative_to(ROOT)} ({text.count(chr(10))} lines)")
        return 0
    if args.check:
        current = TARGET.read_text() if TARGET.is_file() else None
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run python tools/cli_reference.py --write")
            return 1
        print(f"{TARGET.relative_to(ROOT)} is current")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
